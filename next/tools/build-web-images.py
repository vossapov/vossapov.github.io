"""Build lightweight WebP derivatives for every raster image the redesign references.

Sources: image paths found in next/data.js, next/presentation-data.js and next/ai-content.js.
Originals stay untouched (fallback, viewer "open original file", provenance).

  next/assets/web/<original path>.webp     on-screen version, <= 2400px wide (only if it saves >= 25%)
  next/assets/web-thumb/<original path>.webp  360px wide, for timeline / dialog thumbnails
  next/webp-map.js   window.VI_WEBP = { "<orig>": ["<full or empty>", "<thumb>"] }

Run:  python next/tools/build-web-images.py           (incremental)
      python next/tools/build-web-images.py --check   (exit 1 if map/derivatives are stale)
"""
import json, re, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SOURCES = ['next/data.js', 'next/presentation-data.js', 'next/ai-content.js']
RE = re.compile(r'"(/(?:next/)?assets/[^"]+?\.(?:png|jpe?g))"|\'(/(?:next/)?assets/[^\']+?\.(?:png|jpe?g))\'', re.I)
MAX_W, THUMB_W, Q_FULL, Q_THUMB = 2400, 360, 82, 78
check = '--check' in sys.argv

paths = set()
for s in SOURCES:
    for m in RE.finditer((ROOT / s).read_text(encoding='utf-8')):
        paths.add(m.group(1) or m.group(2))

def out(sub, rel):
    return ROOT / 'next/assets' / sub / (rel.lstrip('/') + '.webp')

def save(src_im, dst, width, q):
    im = src_im
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.Resampling.LANCZOS)
    dst.parent.mkdir(parents=True, exist_ok=True)
    im.save(dst, 'WEBP', quality=q, method=6)

mapping, stale, before, after = {}, [], 0, 0
for rel in sorted(paths):
    src = ROOT / rel.lstrip('/')
    if not src.exists():
        continue
    full, thumb = out('web', rel), out('web-thumb', rel)
    fresh = lambda d: d.exists() and d.stat().st_mtime >= src.stat().st_mtime
    need_full, need_thumb = not fresh(full), not fresh(thumb)
    if (need_full or need_thumb) and check:
        stale.append(rel); continue
    if need_full or need_thumb:
        with Image.open(src) as im0:
            im = im0.convert('RGBA' if im0.mode in ('RGBA', 'LA', 'P') and ('transparency' in im0.info or im0.mode != 'P') else 'RGB')
            if need_full: save(im, full, MAX_W, Q_FULL)
            if need_thumb: save(im, thumb, THUMB_W, Q_THUMB)
    use_full = full.stat().st_size <= 0.75 * src.stat().st_size
    before += src.stat().st_size
    after += full.stat().st_size if use_full else src.stat().st_size
    mapping[rel] = ['/' + str(full.relative_to(ROOT)) if use_full else '', '/' + str(thumb.relative_to(ROOT))]

js = ('/* GENERATED by next/tools/build-web-images.py — do not edit by hand. */\n'
      'window.VI_WEBP = ' + json.dumps(mapping, separators=(',', ':'), sort_keys=True) + ';\n')
map_file = ROOT / 'next/webp-map.js'
if check:
    if stale or not map_file.exists() or map_file.read_text() != js:
        print('web images stale:', len(stale), 'derivatives;', 'map differs' if map_file.exists() and map_file.read_text() != js else '')
        sys.exit(1)
    print(f'web images fresh: {len(mapping)} images')
    sys.exit(0)
map_file.write_text(js)
print(f'{len(mapping)} images; on-screen bytes {before/1e6:.1f} MB -> {after/1e6:.1f} MB')
